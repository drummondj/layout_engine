"""
Building a project: Layout Engine from source with the project's extensions
(LE_EXTENSION_DIRS), as a superbuild - .le/superbuild/CMakeLists.txt adds
Layout Engine with add_subdirectory, the way a hand-written one does -
configured in .le/build and installed as a bundle in .le/bundle. Fetched
dependencies' sources - never their builds - are shared between projects in
the source cache (source_cache_dir()), codegen runs on le's own Python
environment (python_env), and ccache is used when it's on PATH. With
`[build] toolchain = true` every step runs inside le's toolchain (toolchain.py)
instead, with its compilers, ccache and Python.
"""

import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import List, Optional, Tuple

from le import python_env, sources
from le.toolchain import Toolchain


class BuildError(Exception):
    pass


def layout_engine_versions(source_dir: Path) -> Tuple[str, int]:
    """(project version, extension API version) declared by a Layout Engine source tree."""
    cmake = (source_dir / "CMakeLists.txt").read_text()
    version = re.search(r"^project\(layout_engine_backend VERSION (\d+\.\d+\.\d+)", cmake, re.M)
    api = re.search(r"^set\(LE_EXTENSION_API_VERSION (\d+)\)", cmake, re.M)
    if not version or not api:
        raise BuildError(f"{source_dir} doesn't look like a Layout Engine source tree with extension support (0.2 or later)")
    return version.group(1), int(api.group(1))


def schema_version(source_dir: Path) -> Optional[str]:
    """The database schema version a Layout Engine source tree declares, if it can be read."""
    schema = source_dir / "src" / "database" / "schema.py"
    if not schema.is_file():
        return None
    found = re.search(r'^\s*version="(\d+\.\d+\.\d+)"', schema.read_text(), re.M)
    return found.group(1) if found else None


def default_jobs(jobs: Optional[int]) -> int:
    """Parallel build jobs: [build] jobs, else LE_BUILD_JOBS, else every CPU."""
    if jobs:
        return jobs
    if os.environ.get("LE_BUILD_JOBS", "").isdigit() and int(os.environ["LE_BUILD_JOBS"]) > 0:
        return int(os.environ["LE_BUILD_JOBS"])
    return os.cpu_count() or 2


def _run(command: List[str], what: str, toolchain: Optional[Toolchain] = None) -> None:
    print(f"le: {what}", flush=True)
    if toolchain is not None:
        command = toolchain.wrap(command)
    result = subprocess.run(command)
    if result.returncode != 0:
        raise BuildError(f"{what} failed (exit {result.returncode}): {' '.join(command)}")


SUPERBUILD = """\
# Generated by `le` - a superbuild embedding Layout Engine; le passes
# LE_EXTENSION_DIRS when it configures.
cmake_minimum_required(VERSION 3.25)
project(le_project CXX)
enable_testing()
add_subdirectory({source} layout_engine)
"""


def write_superbuild(le_source: Path, directory: Path) -> Path:
    """The project's superbuild CMakeLists.txt, adding `le_source` with add_subdirectory."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "CMakeLists.txt"
    text = SUPERBUILD.format(source="[[" + str(le_source.resolve()) + "]]")
    if not path.exists() or path.read_text() != text:  # unchanged, so cmake doesn't reconfigure for nothing
        path.write_text(text)
    return directory


def _cached_source(build_dir: Path) -> Optional[str]:
    cache = build_dir / "CMakeCache.txt"
    if not cache.is_file():
        return None
    found = re.search(r"^CMAKE_HOME_DIRECTORY:INTERNAL=(.*)$", cache.read_text(), re.M)
    return found.group(1) if found else None


def source_cache_dir() -> Path:
    """Where fetched dependency sources are shared: LE_DEPS_DIR, else <cache>/sources."""
    return Path(os.environ.get("LE_DEPS_DIR") or sources.cache_dir() / "sources")


def remove_old_dependency_cache() -> None:
    """Older le shared whole dependency builds in <cache>/deps/<version>; nothing uses it now."""
    old = sources.cache_dir() / "deps"
    if old.is_dir():
        print(f"le: removing the old shared dependency builds in {old} (only sources are shared now)", flush=True)
        shutil.rmtree(old, ignore_errors=True)


def configure_command(superbuild: Path, build_dir: Path, build_type: str, extension_dirs: List[Path],
                      cmake_args: Optional[List[str]] = None, python: Optional[Path] = None,
                      toolchain: Optional[Toolchain] = None) -> List[str]:
    """The cmake configure command. Dependencies build in build_dir's own _deps
    (-U drops a shared FETCHCONTENT_BASE_DIR an older le cached there); only
    their sources come from the shared cache. `python` is codegen's Python;
    a toolchain brings its own, and its compilers, before cmake_args (which
    can still override them)."""
    command = [
        "cmake",
        "-S", str(superbuild),
        "-B", str(build_dir),
        f"-DCMAKE_BUILD_TYPE={build_type}",
        "-DLE_EXTENSION_DIRS=" + ";".join(str(d) for d in extension_dirs),
        "-UFETCHCONTENT_BASE_DIR",
        f"-DLE_SOURCE_CACHE_DIR={source_cache_dir()}",
    ]
    if toolchain is not None:
        command += toolchain.cmake_args()
    elif python is not None:
        command.append(f"-DPython3_EXECUTABLE={python}")
    command += cmake_args or []
    ccache = toolchain.ccache if toolchain is not None else shutil.which("ccache")
    if ccache:
        command += [f"-DCMAKE_C_COMPILER_LAUNCHER={ccache}", f"-DCMAKE_CXX_COMPILER_LAUNCHER={ccache}"]
    return command


def populate_source_cache(build_dir: Path, cache: Path) -> List[str]:
    """Copies each dependency source the configure in build_dir downloaded into
    `cache` (listed in layout_engine/le_fetched_sources.json); returns the
    entries added. Each copy is renamed into place whole, so a concurrent
    `le` never sees half of one, and the first to finish wins."""
    listing = build_dir / "layout_engine" / "le_fetched_sources.json"
    if not listing.is_file():
        return []
    added = []
    for dependency in json.loads(listing.read_text()):
        target = cache / dependency["entry"]
        source = Path(dependency["source_dir"])
        if target.exists() or not source.is_dir() or source.resolve() == target.resolve():
            continue
        cache.mkdir(parents=True, exist_ok=True)
        staging = Path(tempfile.mkdtemp(prefix=f".{dependency['entry']}-", dir=cache))
        try:
            copy = staging / "source"
            shutil.copytree(source, copy, symlinks=True)
            copy.rename(target)
            added.append(dependency["entry"])
        except OSError:
            if not target.exists():
                raise
        finally:
            shutil.rmtree(staging, ignore_errors=True)
    return added


def configure(
    le_source: Path,
    extension_dirs: List[Path],
    state_dir: Path,
    build_type: str,
    cmake_args: Optional[List[str]] = None,
    toolchain: Optional[Toolchain] = None,
) -> Path:
    """Writes the superbuild and configures it in state_dir/build, sharing
    dependency sources through the cache; returns the build directory."""
    build_dir = state_dir / "build"
    superbuild = write_superbuild(le_source, state_dir / "superbuild")
    cached = _cached_source(build_dir)
    if cached is not None and Path(cached).resolve() != superbuild.resolve():
        shutil.rmtree(build_dir)  # configured from another source tree (an older le): cmake refuses to switch
    # Which toolchain the build tree was configured with: cmake can't switch
    # compilers in place, so a different one starts the tree afresh.
    # A tree with no marker predates it, so it used the system's.
    marker = build_dir / "le_toolchain.txt"
    wanted = toolchain.key if toolchain is not None else "system"
    configured = marker.read_text().strip() if marker.is_file() else "system" if (build_dir / "CMakeCache.txt").is_file() else None
    if configured is not None and configured != wanted:
        shutil.rmtree(build_dir)
    remove_old_dependency_cache()
    python = None
    if toolchain is None:
        try:
            python = python_env.codegen_python(le_source, cmake_args)
        except python_env.PythonEnvError as e:
            raise BuildError(str(e)) from e
    _run(configure_command(superbuild, build_dir, build_type, extension_dirs, cmake_args, python, toolchain), "configuring", toolchain)
    build_dir.mkdir(parents=True, exist_ok=True)
    marker.write_text(wanted + "\n")
    populate_source_cache(build_dir, source_cache_dir())
    return build_dir


def build(
    le_source: Path,
    extension_dirs: List[Path],
    state_dir: Path,
    build_type: str,
    jobs: Optional[int],
    startup: Optional[Path],
    cmake_args: Optional[List[str]] = None,
    toolchain: Optional[Toolchain] = None,
) -> Path:
    """Configures, builds and installs; returns the bundle directory."""
    build_dir = configure(le_source, extension_dirs, state_dir, build_type, cmake_args, toolchain)
    bundle_dir = state_dir / "bundle"
    _run(["cmake", "--build", str(build_dir), "--target", "le_shell", "le_tcl", "-j", str(default_jobs(jobs))], "building", toolchain)
    if bundle_dir.exists():
        shutil.rmtree(bundle_dir)  # so a removed extension's files don't linger
    _run(["cmake", "--install", str(build_dir), "--component", "bundle", "--prefix", str(bundle_dir)], "installing", toolchain)

    if startup is not None:
        index_path = bundle_dir / "extensions.json"
        index = json.loads(index_path.read_text())
        index["startup"] = os.path.relpath(startup, bundle_dir)
        index_path.write_text(json.dumps(index, indent=2) + "\n")
    return bundle_dir
